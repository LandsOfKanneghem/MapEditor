// node scripts/sync-equipment.cjs [path-to-Battle]
// Export the actual Battle definitions without depending on its combat/UI scripts at runtime.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const editor = path.resolve(__dirname, '..');
const battle = path.resolve(process.argv[2] ?? path.join(editor, '../Battle'));
const context = { window: null };
context.window = context;
vm.createContext(context);
const scripts = [...fs.readFileSync(path.join(battle, 'index.html'), 'utf8')
  .matchAll(/src="(data\/[^\"]+\.js)"/g)].map(match => match[1]);
for (const file of scripts) vm.runInContext(fs.readFileSync(path.join(battle, file), 'utf8'), context, { filename: file });
const defaults = Object.fromEntries(Object.values(context.CREATURE_TEMPLATES)
  .filter(hero => hero.Equipment).map(hero => [hero.type, Object.fromEntries(Object.keys(context.EQUIPMENT_SLOTS)
    .map(slot => [slot, hero.Equipment[slot]?.id ?? null]))]));
const catalog = { items: context.EQUIPMENT_ITEMS, defaults };
fs.writeFileSync(path.join(editor, 'equipmentCatalog.js'),
  '// Generated by scripts/sync-equipment.cjs from Battle item definitions.\n' +
  '((root) => {\n  const catalog = ' + JSON.stringify(catalog, null, 2) + ';\n' +
  "  if (typeof module !== 'undefined' && module.exports) module.exports = catalog;\n" +
  "  else root.EquipmentCatalog = catalog;\n})(typeof window === 'undefined' ? globalThis : window);\n");
for (const item of Object.values(catalog.items)) {
  const destination = path.join(editor, item.iconPath);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.copyFileSync(path.join(battle, item.iconPath), destination);
}
for (const name of ['head', 'boots', 'gloves', 'belt', 'chest', 'sword', 'shield', 'ring']) {
  const file = `assets/equipment/empty-${name}.png`;
  fs.copyFileSync(path.join(battle, file), path.join(editor, file));
}
fs.mkdirSync(path.join(editor, 'assets/homm2'), { recursive: true });
fs.copyFileSync(path.join(battle, 'assets/homm2/leather.png'), path.join(editor, 'assets/homm2/leather.png'));
console.log(`Exported ${Object.keys(catalog.items).length} items and ${Object.keys(defaults).length} heroes.`);
